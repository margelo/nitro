import { existsSync } from 'fs'
import { mkdir, writeFile } from 'fs/promises'
import path from 'path'
import type { ClassDeclaration } from 'ts-morph'
import { z } from 'zod'
import type { DecoratorOptions, LiteralOptions, LiteralValue } from './getHybridObjectDecoratorOptions.js'
import { getHybridClassOutputDirectory } from './createHybridClassRuntime.js'
import { getHybridClassReExports } from './hybridClassReExports.js'
import { prettifyDirectory } from './prettifyDirectory.js'
import { readJsonFile } from './readJsonFile.js'
import { getNitroModuleDirectory } from './utils.js'

const HYBRID_CLASS_MANIFEST_NAME = 'hybrid-classes.json'
const HYBRID_CLASS_MANIFEST_VERSION = 2

const literalValueSchema: z.ZodType<LiteralValue, LiteralValue> = z.lazy(() =>
  z.union([z.string(), z.boolean(), z.array(literalValueSchema), z.record(z.string(), literalValueSchema)])
)
const literalOptionsSchema = z.record(z.string(), literalValueSchema)
const hybridClassPlatformsSchema = z.strictObject({
  apple: literalOptionsSchema.optional(),
  android: literalOptionsSchema.optional(),
})
const hybridClassManifestSchema = z.strictObject({
  version: z.literal(HYBRID_CLASS_MANIFEST_VERSION, {
    error: 'Unsupported version. Regenerate this file with the nitrogen version that reads it.',
  }),
  classes: z.record(z.string(), hybridClassPlatformsSchema),
})
type HybridClassPlatforms = z.input<typeof hybridClassPlatformsSchema>
type HybridClassManifest = z.input<typeof hybridClassManifestSchema>

/** A HybridObject class and the platform options of its decorators. */
export interface HybridClassManifestEntry {
  name: string
  platforms: DecoratorOptions
}

interface WriteHybridClassManifestOptions {
  hybridClasses: readonly HybridClassManifestEntry[]
  outputDirectory: string
}

/** Returns the path of the manifest in Nitrogen's output directory. */
export function getHybridClassManifestPath(outputDirectory: string): string {
  return path.join(outputDirectory, HYBRID_CLASS_MANIFEST_NAME)
}

/**
 * Writes the decorator options of all classes to `hybrid-classes.json` and
 * returns its path. tsc drops decorators from `.d.ts` output, so packages
 * that extend these classes through built declarations read them from there.
 */
export async function writeHybridClassManifest({ hybridClasses, outputDirectory }: WriteHybridClassManifestOptions): Promise<string> {
  const sortedClasses = hybridClasses.toSorted((a, b) => compareKeys(a.name, b.name))
  const classEntries = sortedClasses.map((hybridClass): [string, HybridClassPlatforms] => [
    hybridClass.name,
    getSortedPlatforms(hybridClass.platforms),
  ])
  // Typed as the reader's input, so the reader accepts everything written here.
  const manifest: HybridClassManifest = {
    version: HYBRID_CLASS_MANIFEST_VERSION,
    classes: Object.fromEntries(classEntries),
  }
  const manifestCode = JSON.stringify(manifest, null, 2)
  const manifestPath = getHybridClassManifestPath(outputDirectory)
  await mkdir(outputDirectory, { recursive: true })
  await writeFile(manifestPath, manifestCode + '\n', 'utf8')
  return manifestPath
}

/**
 * Returns the decorator options of a class declared without decorators in a
 * package's `.nitro.d.ts` output, from the manifest in that package's
 * output directory.
 */
export function getHybridClassManifestOptions(declaration: ClassDeclaration, name: string): DecoratorOptions {
  const filePath = declaration.getSourceFile().getFilePath()
  const reason = `${name}: ${prettifyDirectory(filePath)} declares this class without platform decorators, which tsc removes from .d.ts files.`
  const publishHint =
    'Run Nitrogen in that package and publish it with nitro.json and the output directory (nitrogen/generated by default).'
  const nitroModuleDirectory = getNitroModuleDirectory(filePath)
  if (nitroModuleDirectory == null) {
    throw new Error(`${reason} Nitrogen needs the nitro.json of that package, but no nitro.json was found above that file. ${publishHint}`)
  }
  const outputDirectory = getPackageOutputDirectory(declaration, name, nitroModuleDirectory)
  const manifestPath = getHybridClassManifestPath(outputDirectory)
  const manifestName = prettifyDirectory(manifestPath)
  if (!existsSync(manifestPath)) {
    throw new Error(`${reason} Nitrogen reads them from ${manifestName}, which does not exist. ${publishHint}`)
  }
  const manifest = readJsonFile(manifestPath, hybridClassManifestSchema)
  const platforms = manifest.classes[name]
  if (platforms == null) {
    throw new Error(`${reason} Nitrogen reads them from ${manifestName}, which does not list ${name}. ${publishHint}`)
  }
  return platforms
}

/**
 * Returns the output directory of the Nitrogen run that generated a class.
 * The class's `#nitro/<ClassName>` re-export resolves to its runtime module
 * there. Without a resolvable re-export, e.g. when a nested package.json has
 * no "imports", this falls back to `nitrogen/generated` next to nitro.json.
 */
function getPackageOutputDirectory(declaration: ClassDeclaration, name: string, nitroModuleDirectory: string): string {
  const reExport = getHybridClassReExports(declaration.getSourceFile()).find(
    (hybridClassReExport) => hybridClassReExport.className === name
  )
  const runtimeFile = reExport?.declaration.getModuleSpecifierSourceFile()
  if (runtimeFile != null) {
    return getHybridClassOutputDirectory(runtimeFile.getFilePath())
  }
  return path.join(nitroModuleDirectory, 'nitrogen', 'generated')
}

/** Sorts keys at every level, so the manifest doesn't depend on declaration order. */
function getSortedPlatforms(platforms: DecoratorOptions): HybridClassPlatforms {
  const sortedPlatforms: HybridClassPlatforms = {}
  if (platforms.android != null) {
    sortedPlatforms.android = sortLiteralOptions(platforms.android)
  }
  if (platforms.apple != null) {
    sortedPlatforms.apple = sortLiteralOptions(platforms.apple)
  }
  return sortedPlatforms
}

function sortLiteralOptions(options: LiteralOptions): LiteralOptions {
  const sortedEntries = Object.entries(options)
    .toSorted(([a], [b]) => compareKeys(a, b))
    .map(([key, value]): [string, LiteralValue] => [key, sortLiteralValue(value)])
  return Object.fromEntries(sortedEntries)
}

function sortLiteralValue(value: LiteralValue): LiteralValue {
  if (typeof value !== 'object') return value
  if (Array.isArray(value)) return value.map(sortLiteralValue)
  return sortLiteralOptions(value)
}

/** Compares UTF-16 code units, so the order doesn't depend on the locale. */
function compareKeys(a: string, b: string): number {
  return a < b ? -1 : 1
}
