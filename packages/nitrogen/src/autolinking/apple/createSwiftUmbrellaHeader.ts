import { NitroConfig } from '../../config/NitroConfig.js'
import type { SwiftType } from '../../syntax/swift/types/SwiftType.js'
import { createFileMetadataString } from '../../syntax/helpers.js'
import type { SourceFile, SourceImport } from '../../syntax/SourceFile.js'
import { getImportCode, getImportsCode } from '../../syntax/getImportCode.js'
import { createForeignTypeMetadataPragmas } from './createSwiftForeignTypeMetadata.js'

export function getUmbrellaHeaderName(config = NitroConfig.current): string {
  const moduleName = config.getAppleModuleName()
  return `${moduleName}-Swift-Cxx-Umbrella.hpp`
}

export function createSwiftUmbrellaHeader(types: SwiftType[], moduleDependencies: NitroConfig[]): SourceFile {
  const moduleName = NitroConfig.current.getAppleModuleName()
  const filename = getUmbrellaHeaderName()

  const dependencyIncludes = getImportsCode(
    moduleDependencies.map<SourceImport>((config) => ({
      language: 'c++',
      declaration: config.getCxxHeader(getUmbrellaHeaderName(config), 'private'),
    })),
    'implementation'
  )
  const implementationIncludes = getImportsCode(
    types.flatMap((t) => t.getRequiredImports('c++', 'implementation')),
    'implementation'
  )
  const bridgeInclude = getImportCode({
    language: 'c++',
    declaration: NitroConfig.current.getAppleCxxHeader(),
  })
  // TODO: Remove with ImportedCxxRecord.ts once our minimum Xcode includes
  // https://github.com/swiftlang/swift/pull/93293.
  const foreignTypeMetadataPragmas = createForeignTypeMetadataPragmas(types)
  // TODO: Include the bridge header before the NitroModules umbrella again once our
  // minimum Xcode includes https://github.com/swiftlang/swift/pull/93299 (see getSwiftGenericImport.ts).

  const code = `
${createFileMetadataString(filename, '///')}

#pragma once
${foreignTypeMetadataPragmas}
// Private C++ implementation includes. Never import this umbrella from Swift.
// Include Swift defined types. They define swift::Optional and swift::Array,
// which the C++ helpers below only forward-declare for Swift's importer.
#include <NitroModules/NitroModules-Swift-Cxx-Umbrella.hpp>

// C++ helpers for Swift
${bridgeInclude}
${dependencyIncludes}
#if __has_include("${moduleName}-Swift.h")
// This header is generated by Xcode/Swift on every app build.
// If it cannot be found, make sure the Swift module's name (= podspec name) is actually "${moduleName}".
#include "${moduleName}-Swift.h"
// Same as above, but used when building with frameworks (\`use_frameworks\`)
#elif __has_include(<${moduleName}/${moduleName}-Swift.h>)
#include <${moduleName}/${moduleName}-Swift.h>
#else
#error ${moduleName}'s autogenerated Swift header cannot be found! Make sure the Swift module's name (= podspec name) is actually "${moduleName}", and try building the app first.
#endif

${implementationIncludes}
`.trim()

  return {
    content: code,
    language: 'c++',
    name: filename,
    platform: 'apple',
    subdirectory: ['c++'],
  }
}
