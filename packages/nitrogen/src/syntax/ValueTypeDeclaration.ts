import path from 'node:path'
import type { Project, SourceFile, Type } from 'ts-morph'
import { NitroConfig } from '../config/NitroConfig.js'
import { getHybridObjectSpec } from '../createPlatformSpec.js'
import { getHybridObjectPlatforms, isSomeHybridObject, type Language } from '../getPlatformSpecs.js'
import { getHybridObjectNitroModuleConfig, getNitroModuleDirectory } from '../utils.js'
import type { TypeParsingTarget } from './createType.js'
import { getAllReferencedTypes } from './getAllTypes.js'
import { StructType } from './types/StructType.js'
import { EnumType } from './types/EnumType.js'

interface NativeValues {
  'swift': Set<string>
  'kotlin': Set<string>
  'c++': Set<string>
}
const ownerValues = new WeakMap<Project, Map<string, NativeValues>>()

/** The public native projections generated by this package's declared APIs. */
function readNativeValues(file: SourceFile, directory: string, config: NitroConfig): NativeValues {
  const values: NativeValues = { 'swift': new Set(), 'kotlin': new Set(), 'c++': new Set() }
  const project = file.getProject()
  const fileSystem = project.getFileSystem()
  const suffix = file.isDeclarationFile() ? '*.nitro.d.ts' : '*.nitro.ts'
  const pattern = path.join(directory, '**', suffix)
  const excluded = config.getIgnorePaths().map((entry) => '!' + path.join(directory, entry))
  const paths = fileSystem.globSync([pattern, '!' + path.join(directory, '**/node_modules/**'), ...excluded])
  const namespace = config.getCxxNamespace('c++')
  for (const specPath of paths) {
    if (getNitroModuleDirectory(specPath) !== directory) continue
    const source = project.addSourceFileAtPath(specPath)
    for (const declaration of source.getClasses()) {
      const type = declaration.getType()
      if (!isSomeHybridObject(type)) continue
      const implementations = getHybridObjectPlatforms(declaration)
      for (const platform of ['apple', 'android'] as const) {
        const options = implementations[platform]
        if (options == null) continue
        // References to other HybridObjects do not contribute value declarations to this API.
        const target: TypeParsingTarget = { language: platform === 'apple' ? 'swift' : 'kotlin', platform, collectValueDeclarations: true }
        const spec = getHybridObjectSpec(type, platform, options, target)
        for (const value of getAllReferencedTypes(spec)) {
          if (!(value instanceof StructType || value instanceof EnumType)) continue
          if (value.sourceConfig.getCxxNamespace('c++') !== namespace) continue
          const name = value instanceof StructType ? value.structName : value.enumName
          values[options.language].add(name)
        }
      }
    }
  }
  return values
}

export class ValueTypeDeclaration {
  private readonly directory?: string

  private constructor(
    private readonly name: string,
    readonly sourceConfig: NitroConfig,
    private readonly file?: SourceFile
  ) {
    if (file != null) this.directory = getNitroModuleDirectory(file.getFilePath())
  }

  static fromType(name: string, type: Type, collecting: boolean | undefined): ValueTypeDeclaration {
    const config = getHybridObjectNitroModuleConfig(type) ?? NitroConfig.current
    if (collecting || !config.isExternalConfig) return new ValueTypeDeclaration(name, config)
    const symbol = type.getSymbol() ?? type.getAliasSymbol()
    const node = symbol?.getDeclarations()[0]
    return new ValueTypeDeclaration(name, config, node?.getSourceFile())
  }

  getOwner(language: Language, consumer: NitroConfig = NitroConfig.current): NitroConfig {
    const directory = this.directory
    if (directory == null || this.file == null) return consumer
    const project = this.file.getProject()
    let catalog = ownerValues.get(project)
    if (catalog == null) {
      catalog = new Map()
      ownerValues.set(project, catalog)
    }
    let values = catalog.get(directory)
    if (values == null) {
      values = readNativeValues(this.file, directory, this.sourceConfig)
      catalog.set(directory, values)
    }
    return values[language].has(this.name) ? this.sourceConfig : consumer
  }
}
